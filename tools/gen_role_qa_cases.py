def main() -> None:
    seen = set()
    for item in CASES:
        key = (item["role"], item["question"])
        if key in seen:
            raise SystemExit(f"重复案例: {key}")
        seen.add(key)
        if not item["conclusion"]:
            raise SystemExit(f"案例缺结论: {key}")
    payload = {
        "version": 1,
        "note": "岗位问答案例：真实链路未形成完整结论时的可答性兜底（不抢真实结论）",
        "cases": [dict(id=f"RQ-{i:03d}", **item) for i, item in enumerate(CASES, 1)],
    }
    OUT.write_text(
        "# 岗位问答案例（R2 可答性兜底）——由 tools/gen_role_qa_cases.py 生成\n"
        "# 规则：真实链路（Text2SQL/场景/Agentic）能形成完整结论时一律用真实结论；\n"
        "# 只有人工兜底/空报告/降级/步数用尽/闲聊误判时，才用本文件案例补齐并标注案例编号。\n"
        # width 放大：中文长句被折叠会插入换行（加载后变成多余空格），
        # 案例正文必须逐字一致。
        + yaml.safe_dump(payload, allow_unicode=True, sort_keys=False, width=10000),
        encoding="utf-8")
    print(f"写入 {OUT}：{len(CASES)} 条，覆盖岗位 {len({c['role'] for c in CASES})} 个")


if __name__ == "__main__":
    main()
